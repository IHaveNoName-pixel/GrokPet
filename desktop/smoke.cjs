const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { screen } = require('electron');
const { SettingsStore } = require('./settings.cjs');

const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
module.exports = async function smoke(c) {
  const { win, root } = c;
  const errors = [];
  win.webContents.on('console-message', event => { if (event.level === 'error' || event.level === 3) {errors.push(event.message);console.error('Renderer error location:',event.sourceId,event.lineNumber,event.message);} });
  const read = expression => win.webContents.executeJavaScript(expression);
  for (let i = 0; i < 60 && !(await read('!!bot')); i++) await delay(100);
  assert.equal(await read('!!bot && !!bot.body.getAttribute("d")'), true, 'SVG character initialized');
  assert.equal(await read('typeof require'), 'undefined', 'renderer has no Node access');
  assert.equal(await read('getComputedStyle(document.body).backgroundColor'), 'rgba(0, 0, 0, 0)');
  if (process.argv.includes('--pet-smoke-reopen')) {
    const expected = JSON.parse(fs.readFileSync(path.join(root, 'artifacts', 'smoke-restart-expected.json'), 'utf8'));
    assert.equal(await read('bot.shapeName'), 'cloud');
    assert.equal(await read('bot.colorId'), 'cyan');
    assert.equal(await read('settings.size'), 160);
    assert.equal(await read('settings.roam'), false);
    assert.equal(win.isAlwaysOnTop(), false);
    assert.equal(win.getBounds().x, expected.x, 'process restart restores native window X');
    assert.equal(win.getBounds().y, expected.y, 'process restart restores native window Y');
    assert.equal(await read('settings.hudMode'),expected.hudMode);
    assert.equal(await read('settings.hudFontSize'),expected.hudFontSize);
    assert.deepEqual(await read('settings.hudItems'),expected.hudItems);
    fs.writeFileSync(path.join(root, 'artifacts', 'smoke-reopen-report.json'), JSON.stringify({ passed: true, checks: ['real process restart restores position, shape, color, size, roam and topmost'] }, null, 2));
    console.log('Desktop pet process-restart check passed');
    return;
  }
  c.updateSettings({ roam: false, bubbles: true, size: 128, color: 'black', shape: 'blob', alwaysOnTop: true });
  c.setPaused(false);
  await delay(200);
  // Synthetic input has synthetic global coordinates. Freeze real-cursor hit polling for this input-only check.
  c.stopTicker(); c.setIgnored(false);
  // Target the pet's renderer directly so a user switching foreground apps cannot interrupt this fixture.
  win.webContents.debugger.attach('1.3');
  const mouse = (type, x, buttons) => win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', {type,x,y:216,button:'left',buttons,clickCount:1});
  await mouse('mousePressed',180,1);
  await mouse('mouseReleased',180,0);
  await delay(250);
  assert.equal(c.brain.state, 'happy', 'real renderer pointer interaction reaches main');
  assert.equal(await read('bot.state'), 'happy');
  assert.equal(await read('document.getElementById("bubble").classList.contains("show")'), true);
  c.setIgnored(false);
  await mouse('mousePressed',180,1);
  await mouse('mouseMoved',205,1);
  await delay(120);
  assert.equal(c.brain.dragging, true, 'renderer drag threshold enters dragging');
  await mouse('mouseReleased',205,0);
  await delay(120);
  assert.equal(c.brain.dragging, false, 'release leaves dragging');
  assert.equal(c.brain.state, 'bouncing');
  win.webContents.debugger.detach();
  c.startTicker();
  c.updateSettings({ size: 160, color: 'cyan', shape: 'cloud', roam: false, alwaysOnTop: false });
  await delay(250);
  assert.equal(await read('bot.shapeName'), 'cloud');
  assert.equal(await read('getComputedStyle(document.getElementById("pet-hit")).width'), '160px');
  assert.equal(win.isAlwaysOnTop(), false);
  c.persist();
  const reloaded = new SettingsStore(path.join(c.dataDir, 'settings.json')).load();
  assert.equal(reloaded.color, 'cyan');
  assert.equal(reloaded.roam, false);
  assert.equal(reloaded.size, 160);
  c.setPaused(true);
  await delay(100);
  assert.equal(await read('bot.paused'), true);
  const before = await read('bot.last');
  await delay(180);
  assert.equal(await read('bot.last'), before, 'paused pet does not run RAF');
  c.setVisible(false);
  assert.equal(win.isVisible(), false);
  c.setVisible(true);
  c.setPaused(false);
  await delay(200);
  assert.equal(await read('bot.paused'), false);
  c.setVisible(false);
  await delay(100);
  assert.equal(await read('bot.paused'), true, 'hiding an active pet stops its renderer');
  c.setVisible(true);
  await delay(100);
  assert.equal(await read('bot.paused'), false, 'showing an active pet resumes its renderer');
  win.setPosition(-50000, -50000);
  c.keepVisible();
  const bounds = win.getBounds();
  const area = screen.getDisplayMatching(bounds).workArea;
  const recoveredSize=await read('settings.size');assert.ok(bounds.x+180-recoveredSize/2>=area.x&&bounds.y+216-recoveredSize/2>=area.y,'lost pet recovered inside real work area');
  // Repeated smoke runs must not inherit an excited mood that intentionally suppresses idle roaming.
  c.life.values.mood=70;c.life.values.energy=80;
  c.updateSettings({ roam: true,hudMode:'hidden',personality:{...(await read('settings.personality')),activity:'normal',scheduleEnabled:false} });await delay(750);
  c.brain.lastInteraction = Date.now() - 10000;
  c.brain.until = 0; c.brain.nextIdle = Date.now() + 12000;
  // Use the opposite corner from the real pointer so the hover stop does not suppress roaming.
  const cursor = screen.getCursorScreenPoint();
  win.setPosition(cursor.x < area.x + area.width / 2 ? area.x + area.width - 360 : area.x,
    cursor.y < area.y + area.height / 2 ? area.y + area.height - 480 : area.y);
  c.keepVisible();
  const roamStart = win.getBounds().x;
  await delay(650);
  assert.notEqual(win.getBounds().x, roamStart, 'idle pet moves its real native window');
  c.updateSettings({ roam: false });
  const stopped = win.getBounds().x;
  await delay(150);
  assert.equal(win.getBounds().x, stopped, 'roam toggle stops native window movement');
  c.brain.lastInteraction = Date.now() - 95000; c.tick();
  await delay(100);
  assert.equal(await read('bot.state'), 'sleeping');
  c.updateSettings({ size: 128, color: 'black', shape: 'blob', alwaysOnTop: true });
  c.brain.lastInteraction = Date.now(); c.brain.until = 0; c.brain.nextIdle = Date.now() + 12000;
  await delay(1800);
  await read('say("你好，今天也陪着你", 5000)');
  const output = path.join(root, 'artifacts');
  fs.mkdirSync(output, { recursive: true });
  const shot = await win.webContents.capturePage();
  fs.writeFileSync(path.join(output, 'desktop-pet-smoke.png'), shot.toPNG());
  await read('document.body.style.background = "#e9efe5"');
  const preview = await win.webContents.capturePage();
  fs.writeFileSync(path.join(output, 'desktop-pet-preview.png'), preview.toPNG());
  await read('document.body.style.background = "transparent"');
  assert.deepEqual(errors, [], 'no renderer errors');
  const report = { passed: true, electron: process.versions.electron, bounds, area, settingsReopened: reloaded,
    checks: ['SVG rendering', 'transparent background', 'isolated renderer', 'pointer interaction', 'renderer drag lifecycle', 'appearance update', 'always-on-top toggle', 'save and reopen', 'paused RAF stopped', 'hide and show', 'offscreen recovery', 'native window roaming', 'roam toggle stops movement', 'autonomous sleeping', 'no renderer errors'] };
  fs.writeFileSync(path.join(output, 'smoke-report.json'), JSON.stringify(report, null, 2));
  c.updateSettings({ size: 160, color: 'cyan', shape: 'cloud', roam: false, alwaysOnTop: false });
  c.persist();
  await require('./companion-smoke.cjs')(c);
  await require('./activity-smoke.cjs')(c);
  await require('./music-smoke.cjs')(c);
  await require('./assistant-smoke.cjs')(c);
  c.persist();
  fs.writeFileSync(path.join(output, 'smoke-restart-expected.json'), JSON.stringify(c.store.load(), null, 2));
  console.log('Desktop pet smoke passed:', JSON.stringify(report));
};
