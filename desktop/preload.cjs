const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('pet', {
  clipboard:r=>ipcRenderer.invoke('pet:clipboard',r),
  onClipboard:cb=>ipcRenderer.on('pet:clipboard-changed',(_e,v)=>cb(v)),
  dockLayout:value=>ipcRenderer.invoke('pet:dock-layout',value),
  bubbleHold:until=>ipcRenderer.send('pet:bubble-hold',until),
  noticeResult:(id,shown)=>ipcRenderer.send('pet:notice-result',id,shown),
  uiRegions:rects=>ipcRenderer.send('pet:ui-regions',rects),
  pointerReady:()=>ipcRenderer.send('pet:pointer-ready'),
  voice:value=>ipcRenderer.invoke('pet:voice',value),
  voicePhase:value=>ipcRenderer.send('pet:voice-phase',value),
  onVoiceToggle:cb=>ipcRenderer.on('pet:voice-toggle',cb),
  onVoiceCancel:cb=>ipcRenderer.on('pet:voice-cancel',cb),
  onVoiceSettings:cb=>ipcRenderer.on('pet:voice-settings',cb),
  quickChoice:c=>ipcRenderer.invoke('pet:quick-choice',c),
  onRadialPrepare:callback=>ipcRenderer.on('pet:radial-prepare',(_e,value)=>callback(value)),
  radialPrepared:value=>ipcRenderer.send('pet:radial-prepared',value),
  radialCommit:id=>ipcRenderer.sendSync('pet:radial-commit',id),
  onRadialState:callback=>ipcRenderer.on('pet:radial-state',(_e,value)=>callback(value)),
  quickCapture:value=>ipcRenderer.send('pet:quick-capture',value),
  quickStatus:()=>ipcRenderer.invoke('pet:quick-status'),
  quickAction:c=>ipcRenderer.invoke('pet:quick-action',c),
  quickRegions:r=>ipcRenderer.send('pet:quick-regions',r),
  personalitySettings:value=>ipcRenderer.invoke('pet:personality-settings',value),
  systemCommand:c=>ipcRenderer.invoke('pet:system-command',c),
  launchTargets:c=>ipcRenderer.invoke('pet:launch-targets',c),
  focusAction:value=>ipcRenderer.invoke('pet:focus-action',value),
  onOpenApiSettings:callback=>ipcRenderer.on('pet:open-api-settings',callback),
  reminderAction:value=>ipcRenderer.invoke('pet:reminder-action',value),
  sceneAction:value=>ipcRenderer.invoke('pet:scene-action',value),
  ready: () => ipcRenderer.invoke('pet:ready'),
  hudSettings: value => ipcRenderer.invoke('pet:hud-settings', value),
  vscode:r=>ipcRenderer.invoke('pet:vscode',r),
  projects:request=>ipcRenderer.invoke('pet:projects',request),
  workSettings:value=>ipcRenderer.invoke('pet:work-settings',value),
  transferSettings:value=>ipcRenderer.invoke('pet:transfer-settings',value),
  startup: value => ipcRenderer.invoke('pet:startup', value),
  musicSettings:value=>ipcRenderer.invoke('pet:music-settings',value),
  musicCalibrate:value=>ipcRenderer.invoke('pet:music-calibrate',value),
  musicControl:value=>ipcRenderer.invoke('pet:music-control',value),
  assistantInfo:()=>ipcRenderer.invoke('pet:assistant-info'),
  assistantAction:value=>ipcRenderer.invoke('pet:assistant-action',value),
  assistantFocus:value=>ipcRenderer.send('pet:assistant-focus',value),
  onReplyView:callback=>ipcRenderer.on('pet:reply-view',(_event,value)=>callback(value)),
  onAssistant:callback=>ipcRenderer.on('pet:assistant-state',(_event,value)=>callback(value)),
  dockHeight:(value,expanded)=>ipcRenderer.send('pet:dock-height',value,expanded),
  bubbleRegion:value=>ipcRenderer.send('pet:bubble-region',value),
  controlRegion:value=>ipcRenderer.send('pet:control-region',value),
  action: value => { if (['pet', 'drag-start', 'drag-end', 'menu'].includes(value)) ipcRenderer.send('pet:action', value); },
  onState: callback => ipcRenderer.on('pet:state', (_event, state) => callback(state)),
  onSettings: callback => ipcRenderer.on('pet:settings', (_event, value) => callback(value)),
  onGaze: callback => ipcRenderer.on('pet:gaze', (_event, value) => callback(value)),
  onAudioPeak: callback => ipcRenderer.on('pet:audio-peak', (_event, value) => callback(value)),
  onVisibility: callback => ipcRenderer.on('pet:visibility', (_event, value) => callback(value)),
  stats: () => ipcRenderer.invoke('pet:stats-read'),
  companion: action => ipcRenderer.invoke('pet:companion-action', action),
  onStats: callback => ipcRenderer.on('pet:stats', (_event, value) => callback(value)),
  onNotice: callback => ipcRenderer.on('pet:notice', (_event, value) => callback(value)),
});
