'use strict';
const assert=require('node:assert/strict');const fs=require('node:fs');const path=require('node:path');const {Activity}=require('./companion-core.cjs');
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
module.exports=async c=>{
  const read=code=>c.win.webContents.executeJavaScript(code);const previous=await read('window.pet.ready()');
  c.companion.stop();await wait(250);c.stopTicker();c.setPaused(false);
  c.brain.until=0;c.brain.lastInteraction=Date.now();c.brain.nextIdle=Date.now()+60000;
  c.companion.activity=new Activity();c.companion.queue.queue=[];
  c.companion.snapshot.hardware.animation='scared';c.companion.snapshot.hardware.level='critical';
  c.companion.music.ingest({status:'none',state:'stopped'});
  c.updateSettings({hudMode:'always',musicEnabled:true,bubbles:true});
  const output=path.join(c.root,'artifacts');fs.mkdirSync(output,{recursive:true});
  const show=async expected=>{c.companion.emit();c.tick();await wait(100);assert.equal(await read('bot.state'),expected,'rendered '+expected+' outranks critical load');};
  const event=(name,extra={})=>c.companion.receive({kind:'codex',event:name,session:'animation-fixture',turn:'one',...extra});
  event('UserPromptSubmit');await show('thinking');
  event('PreToolUse',{toolId:'search',phase:'searching'});await show('searching');
  event('PostToolUse',{toolId:'search'});event('PreToolUse',{toolId:'edit',phase:'writing'});await show('writing');
  await read('say("正在修改文件",2000);document.body.style.background="#eef1e8"');
  await wait(800);
  fs.writeFileSync(path.join(output,'codex-writing-preview.png'),(await require('./capture-smoke.cjs')(c.win,'writing animation')).toPNG());
  event('PostToolUse',{toolId:'edit',failed:true});await show('confused');event('Stop');await show('sad');
  await read('say("工具执行失败",2000)');await wait(700);
  fs.writeFileSync(path.join(output,'codex-failure-preview.png'),(await require('./capture-smoke.cjs')(c.win,'failure animation')).toPNG());
  event('UserPromptSubmit',{turn:'two'});event('Stop',{turn:'two'});await show('proud');
  c.companion.activity.outcome.at-=1600;await show('celebrate');
  c.companion.activity.celebrateUntil=0;
  c.companion.music.ingest({status:'ready',title:'fixture',artist:'test',state:'playing',observedAt:Date.now()});await show('dictating');
  assert.equal(await read('document.body.classList.contains("music-active")'),true,'music notes remain visible under high load');
  c.companion.music.ingest({status:'none',state:'stopped'});await show('scared');
  c.brain.lastInteraction=Date.now()-95000;await show('sleeping');
  c.brain.interact('pet');await show('waking');
  await read('document.body.style.background="transparent"');
  c.brain.until=0;c.brain.lastInteraction=Date.now();c.updateSettings(previous);c.startTicker();
  fs.writeFileSync(path.join(output,'activity-report.json'),JSON.stringify({passed:true,checks:['thinking/searching/writing/confused/sad/proud/celebrate render above load','music and notes render above load','load renders only at idle','sleep and waking render above load'],boundary:'Injected activity and hardware fixtures; native hook normalization and same-user pipe verified separately.'},null,2));
};
